-- Peptides4Pets research-commerce backbone.
-- Keeps the pet customer journey isolated while reusing the existing order
-- and EFT settlement infrastructure.

create table if not exists public.psa_pets_checkout_consents (
  id bigint generated by default as identity primary key,
  order_id uuid not null unique references public.orders(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete restrict,
  policy_version text not null check (char_length(policy_version) between 1 and 80),
  report_scope_version text not null check (char_length(report_scope_version) between 1 and 80),
  age_confirmed boolean not null check (age_confirmed),
  nutritional_scope_acknowledged boolean not null check (nutritional_scope_acknowledged),
  label_use_acknowledged boolean not null check (label_use_acknowledged),
  report_scope_acknowledged boolean not null check (report_scope_acknowledged),
  marketing_consent boolean not null default false,
  client_accepted_at timestamptz not null,
  accepted_at timestamptz not null default now(),
  statements jsonb not null default '{}'::jsonb check (jsonb_typeof(statements) = 'object'),
  source text not null default 'pets_checkout' check (char_length(source) between 1 and 80)
);

create index if not exists psa_pets_checkout_consents_user_accepted_idx
  on public.psa_pets_checkout_consents (user_id, accepted_at desc);

alter table public.psa_pets_checkout_consents enable row level security;

create policy psa_pets_checkout_consents_owner_or_admin_select
on public.psa_pets_checkout_consents
for select
to authenticated
using (
  user_id = (select auth.uid())
  or (select public.has_role((select auth.uid()), 'admin'::public.app_role))
);

revoke all on table public.psa_pets_checkout_consents from anon, authenticated;
grant select on table public.psa_pets_checkout_consents to authenticated;
grant all on table public.psa_pets_checkout_consents to service_role;
grant usage, select on sequence public.psa_pets_checkout_consents_id_seq to service_role;

create table if not exists public.psa_pets_order_details (
  order_id uuid primary key references public.orders(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete restrict,
  pet_name text not null check (char_length(btrim(pet_name)) between 1 and 120),
  pet_species text not null check (pet_species in ('dog', 'cat', 'horse')),
  storefront text not null default 'pets.peptide-south-africa.com'
    check (storefront = 'pets.peptide-south-africa.com'),
  created_at timestamptz not null default now()
