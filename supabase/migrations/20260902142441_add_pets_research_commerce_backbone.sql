create table if not exists public.psa_pets_lifecycle_events (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  event text not null check (event in (
    'pets_catalog_viewed',
    'pets_research_navigator_started',
    'pets_research_navigator_completed',
    'pets_evidence_opened',
    'pets_waitlist_started',
    'pets_waitlist_joined',
    'pets_collagen_added',
    'pets_checkout_started',
    'pets_checkout_consent_accepted',
    'pets_marketing_consent_granted',
    'pets_order_created',
    'pets_eft_instructions_shown',
    'pets_portal_viewed',
    'pets_portal_orders_viewed',
    'pets_portal_reports_viewed',
    'pets_reorder_started'
  )),
  event_version text not null default '1.0' check (char_length(event_version) between 1 and 40),
  source text not null default 'pets_storefront' check (char_length(source) between 1 and 80),
  session_id text not null check (char_length(session_id) between 1 and 200),
  user_id uuid references auth.users(id) on delete set null,
  order_id uuid references public.orders(id) on delete set null,
  props jsonb not null default '{}'::jsonb
    check (jsonb_typeof(props) = 'object' and octet_length(props::text) <= 8192)
);

create index if not exists psa_pets_lifecycle_events_created_idx
  on public.psa_pets_lifecycle_events (created_at desc);
create index if not exists psa_pets_lifecycle_events_event_created_idx
  on public.psa_pets_lifecycle_events (event, created_at desc);
create index if not exists psa_pets_lifecycle_events_user_created_idx
  on public.psa_pets_lifecycle_events (user_id, created_at desc)
  where user_id is not null;
create index if not exists psa_pets_lifecycle_events_order_idx
  on public.psa_pets_lifecycle_events (order_id)
  where order_id is not null;

alter table public.psa_pets_lifecycle_events enable row level security;

create policy psa_pets_lifecycle_events_anon_insert
on public.psa_pets_lifecycle_events
for insert
to anon
with check (
  event in (
    'pets_catalog_viewed',
    'pets_research_navigator_started',
    'pets_research_navigator_completed',
    'pets_evidence_opened',
    'pets_waitlist_started',
    'pets_waitlist_joined',
    'pets_collagen_added',
    'pets_checkout_started'
  )
  and user_id is null
  and order_id is null
);

create policy psa_pets_lifecycle_events_authenticated_insert
on public.psa_pets_lifecycle_events
for insert
to authenticated
with check (
  (user_id is null or user_id = (select auth.uid()))
  and (
    order_id is null
    or exists (
      select 1 from public.orders
      where orders.id = psa_pets_lifecycle_events.order_id
        and orders.user_id = (select auth.uid())
    )
  )
);

create policy psa_pets_lifecycle_events_owner_or_admin_select
on public.psa_pets_lifecycle_events
for select
to authenticated
using (
  user_id = (select auth.uid())
  or (select public.has_role((select auth.uid()), 'admin'::public.app_role))
);

revoke all on table public.psa_pets_lifecycle_events from anon, authenticated;
grant insert on table public.psa_pets_lifecycle_events to anon;
grant insert, select on table public.psa_pets_lifecycle_events to authenticated;
grant all on table public.psa_pets_lifecycle_events to service_role;

